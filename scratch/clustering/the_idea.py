# Whenever you look at some source of data, it’s likely that the data will 
# somehow form clusters. A dataset showing where millionaires live probably has 
# clusters in places like Beverly Hills and Manhattan.  A dataset showing how
# many hours people work each week probably has a cluster around 40 (and if it’s 
# taken from a state with laws mandating special benefits for people who work at 
# least 20 hours a week, it probably has another cluster right around 19). A 
# dataset of demographics of registered voters likely forms a variety of clusters
# (e.g., “soccer moms,” “bored retirees,” “unemployed millennials”) that pollsters 
#  and political consultants consider relevant.

# Unlike some of the problems we’ve looked at, there is generally no “correct” 
# clustering. An alternative clustering scheme might group some of the “unemployed 
# millennials” with “grad students,” and others with “parents’ basement dwellers.” 
# Neither scheme is necessarily more correct—instead, each is likely more optimal 
# with respect to its own “how good are the clusters?” metric.

# Furthermore, the clusters won’t label themselves.  You’ll have to do that by
# looking at the data underlying each one.
